"""Внутренний пакет навыка Kandinsky: безопасность и прикладная логика.

Код разделён на модули с одной зоной ответственности каждый — так проще читать,
сопровождать и проходить проверку безопасности. Ниже — назначение модулей и
почему они разделены именно так.

  util      — общие мелкие функции (сериализация ответа, валидация аргументов,
              разбор булевых значений). Не зависит от остальных модулей.
  security  — доступ к файловой системе: конфайнмент входных файлов (allowlist по
              реальному пути), формирование пути для сохранения результата, память
              последнего результата. Собрано в одном месте, чтобы всю политику
              доступа к диску можно было проверить целиком.
  config    — чтение и запись настроек навыка, построение транспортного клиента,
              регистрация виджета настроек (одно поле — API-ключ).
  delivery  — показ результата пользователю: встроенное отображение в чате, а если
              оно недоступно — путь к файлу; плюс стандартная короткая подпись.
  endpoints — реестр операций Kandinsky, оркестрация задачи и сборка всех
              инструментов навыка.

Транспортный HTTP-клиент вынесен отдельно в пакет ``lib`` и намеренно ничего не
знает о файлах и каталогах агента: вся политика безопасности живёт здесь, в core.
"""
